function translateDynamicText(value) {
  let translated = value;

  translated = translated.replace(/^(\d+)\s+products$/i, "$1 件商品");
  translated = translated.replace(/^Subtotal\s*·\s*(\d+)\s+items$/i, "小计 · $1 件商品");
  translated = translated.replace(/^Delivery date:\s*(.+)$/i, "配送日期：$1");
  translated = translated.replace(/^The highest price is\s*(.+)$/i, "最高价格为 $1");
  translated = translated.replace(/^View my cart\s*\((\d+)\)$/i, "查看购物车 ($1)");

  Object.entries(inlineZhCN)
    .sort(([a], [b]) => b.length - a.length)
    .forEach(([english, chinese]) => {
      translated = translated.replaceAll(english, chinese);
    });

  return translated;
}

export function getStoredLanguage() {
  return localStorage.getItem(LANGUAGE_STORAGE_KEY) || "en";
}

export function setStoredLanguage(language) {
  localStorage.setItem(LANGUAGE_STORAGE_KEY, language);
  window.dispatchEvent(new CustomEvent(LANGUAGE_CHANGED_EVENT, { detail: { language } }));
}

export function translateText(value, language) {
  if (language !== "zh-CN") {
    return value;
  }

  const normalized = String(value).trim();
  return zhCN[normalized] || translateDynamicText(normalized) || value;
}
